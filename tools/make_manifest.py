#!/usr/bin/env python3
"""Генерация addon/CatQuest335/manifest.lua.

Запускать ПОСЛЕ синтеза: в манифест попадают только реально существующие mp3,
с их настоящей длительностью (ffprobe) — по ней аддон понимает, когда реплика закончилась.

  python tools/make_manifest.py --in data/quests_ru.clean.json --voices addon/CatQuest335_Voices --out addon/CatQuest335/manifest.lua
"""
import argparse, json, os, re, shutil, subprocess, sys

KINDS = ("desc", "desc_f", "comp", "comp_f")


def lua_str(s: str) -> str:
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\r', ' ').replace('\n', ' ')
    return '"' + s + '"'


def norm_ws(s: str) -> str:
    return ' '.join((s or '').split())


def obj_prefix(obj: str, n: int = 60) -> str:
    """Начало текста цели квеста до первого плейсхолдера ($N и т.п. клиент подставит сам)."""
    obj = norm_ws(obj).split('$', 1)[0].rstrip()
    return obj[:n]


def duration(path, ffprobe):
    if ffprobe:
        r = subprocess.run([ffprobe, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                           capture_output=True, text=True)
        try:
            return float(r.stdout.strip())
        except ValueError:
            pass
    # грубо: 64 kbps mono
    return os.path.getsize(path) * 8 / 64000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--in', dest='inp', required=True)
    ap.add_argument('--voices', required=True, help='папка с mp3 (CatQuest335_Voices)')
    ap.add_argument('--out', dest='out', required=True)
    a = ap.parse_args()

    ffprobe = shutil.which("ffprobe")
    if not ffprobe:
        print("ВНИМАНИЕ: нет ffprobe в PATH — длительность будет оценена по размеру файла", file=sys.stderr)

    data = json.load(open(a.inp, encoding='utf-8'))
    lines = ["-- Autogenerated by tools/make_manifest.py — не правится руками",
             "-- v = { kind = длительность в секундах } только для существующих файлов",
             "CatQuest335Manifest = {"]
    titles = {}
    n_files = n_quests = 0
    for q in data:
        qid = int(q['questID'])
        v = {}
        for kind in KINDS:
            p = os.path.join(a.voices, f"{qid}_{kind}.mp3")
            if os.path.isfile(p):
                v[kind] = round(duration(p, ffprobe), 1)
        if not v:
            continue
        n_quests += 1
        n_files += len(v)
        title = norm_ws(q.get('title'))
        vs = ", ".join(f"{k}={d}" for k, d in v.items())
        npc = ", ".join(str(int(n)) for n in (q.get("starters") or []))
        lines.append(
            f'  [{qid}] = {{ title={lua_str(title[:80])}, races={int(q.get("races") or 0)}, '
            f'classes={int(q.get("classes") or 0)}, npc={{ {npc} }}, '
            f'obj={lua_str(obj_prefix(q.get("objective")))}, v={{ {vs} }} }},')
        titles.setdefault(title, []).append(qid)
    lines.append("}")

    # Название -> список ID. Одинаковых названий много (Альянс/Орда, классовые квесты),
    # поэтому всегда список; аддон выбирает нужный по расе/классу/тексту цели.
    lines.append("CatQuest335TitleToID = {")
    for title, ids in titles.items():
        lines.append(f'  [{lua_str(title)}] = {{ {", ".join(map(str, ids))} }},')
    lines.append("}")

    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write("\n".join(lines) + "\n")
    dups = sum(1 for ids in titles.values() if len(ids) > 1)
    print(f"OK: квестов с озвучкой {n_quests}, файлов {n_files}, повторяющихся названий {dups} -> {a.out}")


if __name__ == '__main__':
    main()
