#!/usr/bin/env python3
"""Генерация addon/CatQuest335/manifest.lua из quests_ru.clean.json"""
import argparse, json

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--in', dest='inp', required=True)
    ap.add_argument('--out', dest='out', required=True)
    a = ap.parse_args()
    data = json.load(open(a.inp, encoding='utf-8'))
    lines = ["-- Autogenerated by tools/make_manifest.py — не правится руками",
             "CatQuest335Manifest = CatQuest335Manifest or {"]
    for q in data:
        qid = int(q['questID'])
        title = (q.get('title') or '').replace('"', "'")[:80]
        has_desc = bool(q.get('description'))
        has_comp = bool(q.get('completion'))
        # грубая длительность для таймера проигрывания в 3.3.5: ~900 символов/мин
        def dur(t): return max(4, min(60, int(len(t or '') / 15)))
        lines.append(f'  [{qid}] = {{ title="{title}", has_desc={str(has_desc).lower()}, has_comp={str(has_comp).lower()}, dur={{desc={dur(q.get("description"))}, comp={dur(q.get("completion"))}}} }},')
    lines.append("}")
    open(a.out, 'w', encoding='utf-8').write("\n".join(lines) + "\n")
    print(f"OK: {len(data)} -> {a.out}")

if __name__ == '__main__':
    main()
